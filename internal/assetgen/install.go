// Package assetgen verifies native candidates before generating Go embed files.
package assetgen

import (
	"crypto/sha256"
	"encoding/json"
	"fmt"
	"go/build/constraint"
	"go/format"
	"os"
	"path/filepath"
	"slices"

	"github.com/yuhaiin/purego-sqlite-embed/internal/sqlitesource"
)

type target struct {
	GOOS      string `json:"goos"`
	GOARCH    string `json:"goarch"`
	Libc      string `json:"libc"`
	FloatABI  string `json:"float_abi"`
	MinimumOS string `json:"minimum_os"`
	Tags      string `json:"tags"`
}

type metadata struct {
	Version      string `json:"sqlite_version"`
	RowABI       int    `json:"row_bridge_abi"`
	RowHash      string `json:"row_bridge_sha256"`
	ExecABI      int    `json:"exec_bridge_abi"`
	ExecHash     string `json:"exec_bridge_sha256"`
	GOOS         string `json:"goos"`
	GOARCH       string `json:"goarch"`
	Libc         string `json:"libc"`
	FloatABI     string `json:"float_abi"`
	MinimumOS    string `json:"minimum_os"`
	Filename     string `json:"filename"`
	SHA256       string `json:"sha256"`
	Size         int64  `json:"size"`
	SourceURL    string `json:"source_url"`
	SourceSHA256 string `json:"source_sha256"`
	SourceSHA3   string `json:"source_sha3_256"`
}

type candidate struct {
	key, filename            string
	data, manifest, goSource []byte
}

func hash(data []byte) string { return fmt.Sprintf("%x", sha256.Sum256(data)) }

func Install(root, source string, keys []string) error {
	pin, err := sqlitesource.ReadPin(filepath.Join(root, "scripts/source.json"))
	if err != nil {
		return err
	}
	data, err := os.ReadFile(filepath.Join(root, "scripts/targets.json"))
	if err != nil {
		return err
	}
	var targets map[string]target
	if err := json.Unmarshal(data, &targets); err != nil {
		return err
	}
	row, err := os.ReadFile(filepath.Join(root, "bridge/row.c"))
	if err != nil {
		return err
	}
	exec, err := os.ReadFile(filepath.Join(root, "bridge/exec.c"))
	if err != nil {
		return err
	}
	if len(keys) == 0 {
		entries, err := os.ReadDir(source)
		if err != nil {
			return err
		}
		for _, entry := range entries {
			if entry.IsDir() {
				keys = append(keys, entry.Name())
			}
		}
	}
	if len(keys) == 0 {
		return fmt.Errorf("no native candidates in %s", source)
	}
	keys = slices.Clone(keys)
	slices.Sort(keys)
	var candidates []candidate
	for _, key := range keys {
		t, ok := targets[key]
		if !ok {
			return fmt.Errorf("unknown SQLite target %q", key)
		}
		if _, err := constraint.Parse("//go:build " + t.Tags); err != nil {
			return err
		}
		filename := "libsqlite3.so"
		if t.GOOS == "darwin" {
			filename = "libsqlite3.dylib"
		}
		if t.GOOS == "windows" {
			filename = "sqlite3.dll"
		}
		manifest, err := os.ReadFile(filepath.Join(source, key, "manifest.json"))
		if err != nil {
			return err
		}
		var m metadata
		if err := json.Unmarshal(manifest, &m); err != nil {
			return err
		}
		data, err := os.ReadFile(filepath.Join(source, key, filename))
		if err != nil {
			return err
		}
		want := metadata{Version: pin.Version, RowABI: 1, RowHash: hash(row), ExecABI: 1, ExecHash: hash(exec), GOOS: t.GOOS, GOARCH: t.GOARCH, Libc: t.Libc, FloatABI: t.FloatABI, MinimumOS: t.MinimumOS, Filename: filename, SHA256: hash(data), Size: int64(len(data)), SourceURL: pin.URL, SourceSHA256: pin.SHA256, SourceSHA3: pin.SHA3}
		if m != want {
			return fmt.Errorf("%s: candidate source/ABI metadata or binary integrity mismatch", key)
		}
		generated := fmt.Sprintf(`// Code generated by go generate; DO NOT EDIT.
//go:build %s

package sqliteembed

import _ "embed"

//go:embed assets/%s/%s
var nativeLibrary []byte

//go:embed assets/%s/manifest.json
var nativeManifest []byte

func init() { selected = asset{data: nativeLibrary, manifest: nativeManifest} }
`, t.Tags, key, filename, key)
		formatted, err := format.Source([]byte(generated))
		if err != nil {
			return err
		}
		candidates = append(candidates, candidate{key, filename, data, manifest, formatted})
	}
	// Validate the entire batch before replacing any published file.
	for _, c := range candidates {
		if err := sqlitesource.WriteFile(filepath.Join(root, "assets", c.key, c.filename), c.data); err != nil {
			return err
		}
		if err := sqlitesource.WriteFile(filepath.Join(root, "assets", c.key, "manifest.json"), c.manifest); err != nil {
			return err
		}
		if err := sqlitesource.WriteFile(filepath.Join(root, "asset_"+c.key+".go"), c.goSource); err != nil {
			return err
		}
		fmt.Println("installed " + c.key)
	}
	version := fmt.Sprintf("// Code generated by go generate; DO NOT EDIT.\n\npackage sqliteembed\n\nconst SQLiteVersion = %q\n", pin.Version)
	return sqlitesource.WriteFile(filepath.Join(root, "version.go"), []byte(version))
}
