#!/usr/bin/env python3
"""Verify candidate manifests and generate committed target-specific embed files."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess

from build import ROOT, VERSION, URL, SHA256, SHA3, BRIDGE_ABI, BRIDGE_SHA256


def install(source, keys):
    (ROOT / "version.go").write_text('// Code generated by scripts/install.py; DO NOT EDIT.\n\npackage sqliteembed\n\nconst SQLiteVersion = "' + VERSION + '"\n')
    targets = json.loads((ROOT / "scripts/targets.json").read_text())
    for key in keys:
        target = targets[key]
        candidate = source / key
        manifest = json.loads((candidate / "manifest.json").read_text())
        filename = {"darwin":"libsqlite3.dylib", "windows":"sqlite3.dll"}.get(target["goos"], "libsqlite3.so")
        for name, expected in {"sqlite_version": VERSION, "source_url": URL, "source_sha256": SHA256,
                               "row_bridge_abi": BRIDGE_ABI, "row_bridge_sha256": BRIDGE_SHA256,
                               "source_sha3_256": SHA3, "goos": target["goos"], "goarch": target["goarch"],
                               "libc": target["libc"], "float_abi": target.get("float_abi", ""),
                               "minimum_os": target["minimum_os"], "filename": filename}.items():
            if manifest.get(name) != expected:
                raise SystemExit(f"{key}: unexpected {name}")
        data = (candidate / filename).read_bytes()
        if len(data) != manifest["size"] or hashlib.sha256(data).hexdigest() != manifest["sha256"]:
            raise SystemExit(f"{key}: binary integrity failure")
        destination = ROOT / "assets" / key
        destination.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(candidate / filename, destination / filename)
        shutil.copyfile(candidate / "manifest.json", destination / "manifest.json")
        generated = ROOT / ("asset_" + key + ".go")
        generated.write_text(f'''// Code generated by scripts/install.py; DO NOT EDIT.
//go:build {target['tags']}

package sqliteembed

import _ "embed"

//go:embed assets/{key}/{filename}
var nativeLibrary []byte

//go:embed assets/{key}/manifest.json
var nativeManifest []byte

func init() {{ selected = asset{{data: nativeLibrary, manifest: nativeManifest}} }}
''')
        subprocess.run(["gofmt", "-w", str(generated)], check=True)
        print("installed " + key)


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("source", type=Path)
    p.add_argument("targets", nargs="*")
    args = p.parse_args()
    keys = args.targets or sorted(path.name for path in args.source.iterdir() if path.is_dir())
    install(args.source.resolve(), keys)
